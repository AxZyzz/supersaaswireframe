#!/usr/bin/env node
/**
 * Learning Loop T07: turns replication-set.json (the only tables + columns that
 * may leave Postgres for BigQuery) into the two files that enforce it:
 *   postgres-setup.sql      the datastream_reader role (column-level SELECT only),
 *                           the column-restricted publication and the replication slot
 *   datastream-include.json the Datastream "include objects" list, down to columns
 * so the list lives in ONE place. `node infra/bigquery/generate.js` rewrites both;
 * a Jest test fails if they are out of date.
 */
const fs = require('fs');
const path = require('path');

const ROLE = 'datastream_reader';
const PUBLICATION = 'expelly_bq';
const SLOT = 'expelly_bq_slot';

function render(set) {
  const schema = set.schema;
  const tables = Object.entries(set.tables);
  const cols = (c) => c.map((x) => `"${x}"`).join(', ');

  const grants = tables
    .map(([t, c]) => `GRANT SELECT (${cols(c)}) ON "${schema}"."${t}" TO ${ROLE};`)
    .join('\n');
  const publicationTables = tables
    .map(([t, c]) => `  "${schema}"."${t}" (${cols(c)})`)
    .join(',\n');

  const sql = `-- GENERATED by infra/bigquery/generate.js from replication-set.json. Do not edit by hand.
-- Learning Loop T07: what Postgres lets Datastream read.
--
-- Run ONCE, as the \`postgres\` user, AFTER the Cloud SQL flag
-- cloudsql.logical_decoding=on is set (that restarts the database). Safe to run again.
--
--   psql "host=... dbname=supersaas user=postgres" -v reader_password="$PW" -f postgres-setup.sql
--
-- What it does:
--  1. creates role ${ROLE}: can log in, can replicate, bypasses row-level security
--     (every table has FORCE RLS, so without BYPASSRLS the first backfill would copy 0 rows)
--  2. gives it SELECT on the listed COLUMNS only (not whole tables): even this role
--     cannot read to_email, message bodies, lead names, etc.
--  3. creates publication ${PUBLICATION} listing the same columns (Postgres 15+ column lists),
--     so a column that is not listed never even leaves the database engine
--  4. creates the logical replication slot ${SLOT} (the bookmark Datastream resumes from)
\\set ON_ERROR_STOP on

SELECT format('CREATE ROLE ${ROLE} LOGIN REPLICATION BYPASSRLS PASSWORD %L', :'reader_password')
 WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${ROLE}')
\\gexec

GRANT USAGE ON SCHEMA "${schema}" TO ${ROLE};
${grants}

SELECT 'CREATE PUBLICATION ${PUBLICATION}'
 WHERE NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = '${PUBLICATION}')
\\gexec
ALTER PUBLICATION ${PUBLICATION} SET TABLE
${publicationTables};

SELECT pg_create_logical_replication_slot('${SLOT}', 'pgoutput')
 WHERE NOT EXISTS (SELECT 1 FROM pg_replication_slots WHERE slot_name = '${SLOT}');
`;

  const include = {
    postgresqlSchemas: [
      {
        schema,
        postgresqlTables: tables.map(([t, c]) => ({
          table: t,
          postgresqlColumns: c.map((column) => ({ column })),
        })),
      },
    ],
  };
  return { sql, include: JSON.stringify(include, null, 2) + '\n' };
}

module.exports = { render, ROLE, PUBLICATION, SLOT };

if (require.main === module) {
  const set = JSON.parse(
    fs.readFileSync(path.join(__dirname, 'replication-set.json'), 'utf8'),
  );
  const { sql, include } = render(set);
  fs.writeFileSync(path.join(__dirname, 'postgres-setup.sql'), sql);
  fs.writeFileSync(path.join(__dirname, 'datastream-include.json'), include);
  console.log(`wrote postgres-setup.sql and datastream-include.json (${Object.keys(set.tables).length} tables)`);
}
